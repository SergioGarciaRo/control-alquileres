export const translations: Record<Lang, typeof es> = { es, en }

export type TranslationKey = keyof typeof es

/** Translate a key with optional variable interpolation: {varName} */
export function t(key: TranslationKey, lang: Lang, vars?: Record<string, string | number>): string {
  const dict = translations[lang] as Record<string, string>
  let str = dict[key] ?? (translations.es as Record<string, string>)[key] ?? key
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, String(v))
    })
  }
  return str
}
